grade = int(input("Enter a number"))
if grade >= 90:
    print(f'Your grade is {grade} earns you an A in this course.')
elif grade >= 70:
    print(f'Your grade is {grade} earns you a B in this course.')
elif grade >= 50:
    print(f'Your grade is {grade} earns you a C in this course.')
else:
    print(f'Your grade is {grade} earns you a D in this course.')